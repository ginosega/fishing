#!/usr/bin/env node
/**
 * Compile the canonical JSON Schemas before browser bundling.
 * The generated module is Git-ignored and included as static JavaScript,
 * so the owner PWA never invokes AJV's new Function under strict CSP.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import schema from '../contracts/schema.json' with {type:'json'};

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output=path.join(root,'src/generated/ajv-validators.mjs');
const definitions=Object.freeze({
 validateGearBundle:'gearBundle',
 validateKbBundle:'kbBundle',
 validateCatchBundle:'catchBundle',
 validateGearItem:'gearItem',
 validateKbEntity:'kbEntity',
 validateCatch:'catch',
});

export async function generateStandaloneValidators(){
 const ajv=new Ajv2020({allErrors:true,strict:true,
  code:{source:true,esm:true}});
 const validators={};
 for(const [name,definition] of Object.entries(definitions))
  validators[name]=ajv.compile({$ref:'#/$defs/'+definition,
   $defs:schema.$defs});
 const compiled=standaloneCode(ajv,validators);
 // Do not substitute a string-based runtime compiler; enforce no eval.
 if(/\b(?:new\s+Function|eval\s*\()/.test(compiled))
  throw Error('Standalone validator unexpectedly contains dynamic execution');
 const text='// AUTO-GENERATED by pwa/tools/generate-validators.mjs; DO NOT EDIT.\n'+compiled+'\n';
 await fs.mkdir(path.dirname(output),{recursive:true});
 await fs.writeFile(output,text,'utf8');
 return output;
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))
 generateStandaloneValidators().then(p=>console.log('PASS: static CSP-safe AJV validators generated'),e=>{
  console.error(e);process.exitCode=1;
 });
