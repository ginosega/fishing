#!/usr/bin/env node
/**
 * FISH118 D3: prove reproducible CSP owner bundle with LF and CRLF
 * checkouts. This is a LOCAL, provider-free test; no deployments/writes.
 * Precondition: run normal build-d3-pilot.mjs --check first.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';

const pwa=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const generated=path.resolve(pwa,'../experiments/p3/preview/src/generated');
const paths=[
 path.join(generated,'d3-pilot.bundle.txt'),
 path.join(generated,'d3-pilot.css.txt'),
 path.join(generated,'d3-pilot.bundle.sha256.json'),
 path.join(pwa,'src/generated/d3-validators.mjs'),
];
const sha=b=>createHash('sha256').update(b).digest('hex');
const before=await Promise.all(paths.map(x=>fs.readFile(x)));
let output;
try{
 output=execFileSync(process.execPath,[
  'tools/build-d3-pilot.mjs','--check','--simulate-windows-eol',
 ],{cwd:pwa,encoding:'utf8',stdio:['ignore','pipe','pipe']});
}catch(e){
 console.error('D3_WINDOWS_EOL_TEST_FAILED',String(e.stderr||e.message).slice(0,1000));
 process.exitCode=1;
 process.exit();
}
assert.match(output,/"simulatedWindowsEol":true/);
const after=await Promise.all(paths.map(x=>fs.readFile(x)));
for(let i=0;i<paths.length;i++){
 assert.equal(sha(after[i]),sha(before[i]),
  'CRLF checkout simulation changed generated bytes: '+path.basename(paths[i]));
}
const manifest=JSON.parse(after[2].toString('utf8'));
assert.equal(manifest.sha256,sha(after[0]));
assert.equal(manifest.cssSha256,sha(after[1]));
process.stdout.write(JSON.stringify({
 verified:true,simulatedWindowsCrlf:true,
 exactlyEqualGeneratedArtifacts:paths.length,
 pilotSha256:manifest.sha256,
 cloudflareDeploy:false,
})+'\n');
